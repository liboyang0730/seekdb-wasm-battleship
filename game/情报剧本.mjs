function hashSeed(seed) {
  let value = 2166136261;
  for (const char of String(seed)) value = Math.imul(value ^ char.charCodeAt(0), 16777619);
  value = Math.imul(value ^ value >>> 16, 0x85ebca6b);
  value = Math.imul(value ^ value >>> 13, 0xc2b2ae35);
  return (value ^ value >>> 16) >>> 0;
}

/** 每关六套内容，再组合独立采样/监听渠道；Fork用同seed返回完全相同对象。 */
export function createSignalStory({ level = 1, seed = 1 } = {}) {
  const levelId = typeof level === 'number' ? level : level?.id;
  if (!Number.isInteger(levelId) || levelId < 1 || levelId > 6) throw new RangeError('情报剧本关卡无效');
  const theme = THEMES[levelId - 1];
  const [title, keyword, echoText, listenText] = theme.variants[hashSeed(`${seed}|variant|${levelId}`) % 6];
  const echoSource = ECHO_SOURCES[hashSeed(`${seed}|echo-source|${levelId}`) % ECHO_SOURCES.length];
  const listenSource = LISTEN_SOURCES[hashSeed(`${seed}|listen-source|${levelId}`) % LISTEN_SOURCES.length];
  const vector = theme.vector.map((value, i) => Number(Math.max(0, Math.min(1,
    value + (hashSeed(`${seed}|feature|${levelId}|${i}`) % 31 - 15) / 1000)).toFixed(3)));
  const rotation = hashSeed(`${seed}|archive|${levelId}`) % theme.archives.length;
  return {
    id: `signal-l${levelId}-${hashSeed(seed).toString(16)}`, title,
    echo: { name: 'warship', label: theme.echoLabel, source: echoSource, text: echoText, vector, features: [...SIGNAL_FEATURES] },
    listen: { keyword, label: theme.listenLabel, source: listenSource, text: `${listenText} 本次有效目录词：${keyword}。` },
    feedback: { empty: `“${title}”还没匹配到记录，请核对当前任务与这份监听。`,
      wrongArea: `这份“${title}”属于别的海区，当前会合点还没有对上。` },
    archiveLines: Array.from({ length: 6 }, (_, i) => `${listenSource}旧档：${theme.archives[(rotation + i) % theme.archives.length]}`),
  };
}
