/** 坐标数字独立绘制，不依赖小字号字体的抗锯齿或系统字形。每字7×9像素。 */
export const AXIS_DIGITS = Object.freeze({
  '0':['0111110','1100011','1100011','1100011','1100011','1100011','1100011','1100011','0111110'],
  '1':['0001100','0011100','0111100','0001100','0001100','0001100','0001100','0001100','0111110'],
  '2':['0111110','1100011','0000011','0000110','0001100','0011000','0110000','1100000','1111111'],
  '3':['0111110','1100011','0000011','0000011','0011110','0000011','0000011','1100011','0111110'],
  '4':['0001100','0011100','0111100','1101100','1101100','1111111','0001100','0001100','0001100'],
  '5':['1111111','1100000','1100000','1100000','1111110','0000011','0000011','1100011','0111110'],
  '6':['0011110','0110000','1100000','1100000','1111110','1100011','1100011','1100011','0111110'],
  '7':['1111111','0000011','0000110','0000110','0001100','0001100','0011000','0011000','0011000'],
  '8':['0111110','1100011','1100011','1100011','0111110','1100011','1100011','1100011','0111110'],
  '9':['0111110','1100011','1100011','1100011','0111111','0000011','0000011','0000110','0111100'],
});

export function drawAxisNumber(ctx, value, centerX, centerY, color='#163e58') {
  const label=String(value);
  if(!/^\d{1,2}$/.test(label))return {x:centerX,y:centerY,width:0,height:0};
  const width=label.length*8-1,height=9,x=Math.round(centerX-width/2),y=Math.round(centerY-height/2);
  ctx.fillStyle=color;
  [...label].forEach((digit,index)=>AXIS_DIGITS[digit].forEach((row,dy)=>[...row].forEach((pixel,dx)=>{
    if(pixel==='1')ctx.fillRect(x+index*8+dx,y+dy,1,1);
  })));
  return {x,y,width,height};
}

